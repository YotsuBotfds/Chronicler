def _institution_fit(t: g01.InstitutionType, civ, gov: CivGovernance, world, ctx: _Context) -> float:
    at_war = any(civ.name in pair for pair in world.active_wars)
    hostile = sum(1 for other, rel in world.relationships.get(civ.name, {}).items()
                  if rel.disposition in (Disposition.HOSTILE, Disposition.SUSPICIOUS))
    n_routes = len(ctx.partners.get(civ.name, ()))
    stype = civ.leader.succession_type
    if t is I.MILITARY_ACCLAMATION:
        return 1.0 + (1.0 if stype in ("general", "usurper") else 0.0)
    if t is I.CONSCRIPTION:
        return 1.0 + (1.5 if at_war else 0.0)
    if t is I.FRONTIER_GARRISONS:
        return 1.0 + 0.3 * min(hostile, 5)
    if t is I.MARTIAL_LAW:
        return 0.3 + (2.0 if civ.stability < 25 else 0.0) + (2.0 if gov.psi_crisis else 0.0)
    if t is I.PROPERTY_RIGHTS:
        return 1.0 + civ.economy / 100
    if t is I.FREE_TRADE:
        return 0.5 + 0.5 * min(n_routes, 3)
    if t is I.MERCHANT_COURTS:
        return 0.5 + 0.4 * min(n_routes, 3)
    if t is I.TAX_CODE:
        return 1.0 + (1.0 if gov.fiscal_crisis or civ.treasury < 50 else 0.0)
    if t is I.WRITTEN_LAW:
        return 1.0 + 0.2 * min(len(civ.regions), 5)
    if t is I.PATRONAGE_SYSTEM:
        return 1.0 + civ.culture / 100
    if t is I.EDUCATION:
        return 1.0 + (1.0 if gov.elite_overproduction else 0.0)
    if t is I.REPUBLICAN_VIRTUE:
        return 1.0 + (1.0 if stype == "elected" else 0.0)
    if t is I.TEMPLE_TITHE:
        temples = sum(1 for name in civ.regions for inf in getattr(ctx.region_map.get(name), "infrastructure", ())
                      if getattr(inf, "faith_id", -1) >= 0)
        return 1.0 + 0.5 * min(temples, 4)
    if t is I.DIVINE_RIGHT:
        return 1.0 + (1.0 if gov.ruler_legitimacy < 0.4 else 0.0)
    if t is I.HOLY_INQUISITION:
        faith = getattr(civ, "civ_majority_faith", 0xFF)
        other = sum(1 for name in civ.regions
                    if getattr(ctx.region_map.get(name), "majority_belief", faith) not in (faith, 0xFF))
        return 0.5 + 1.0 * min(other, 3)
    if t is I.COMMONS_MANAGEMENT:
        soils = [ctx.region_map[n].ecology.soil for n in civ.regions if n in ctx.region_map]
        mean_soil = sum(soils) / len(soils) if soils else 1.0
        return 0.5 + (1.5 if mean_soil < 0.5 else 0.0)
    return 1.0


def _proposal_attempts(world, civ_idx: int, civ, gov: CivGovernance, ctx: _Context,
                       snapshot: g01.InstitutionSnapshot,
                       factions: g01.FactionWeights) -> tuple[g01.ProposalAttempt, ...]:
    candidates = g01.proposal_candidates(snapshot, factions)
    if not candidates:
        return ()
    rng = _rng("governance_institution", world, INSTITUTION_OFFSET, civ_idx)
    attempts = []
    for faction in g01.Faction:
        aligned = [t for t in candidates if g01.alignment(t) is faction]
        if not aligned:
            continue
        weights = [max(0.01, _institution_fit(t, civ, gov, world, ctx)) for t in aligned]
        point = rng.random() * math.fsum(weights)
        choice = aligned[-1]
        cumulative = 0.0
        for t, w in zip(aligned, weights):
            cumulative += w
            if point < cumulative:
                choice = t
                break
        attempts.append(g01.ProposalAttempt(choice, rng.random()))
    return tuple(attempts)



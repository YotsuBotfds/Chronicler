# ---------------------------------------------------------------------------
# Phase 2: institutional funding record (M63a bookkeeping)
# ---------------------------------------------------------------------------

def fund_institutions_phase2(world: "WorldState", acc=None) -> list[Event]:
    """Pay enforcement demand after the base governing cost; record coverage.

    Coverage is the aggregate ratio of what the treasury (including this
    turn's already-queued Phase 1-2 debits) can pay; the treasury is never
    pushed into debt for institutions. Recorded as an EXTERNAL_AGGREGATE_RECORD
    funding observation that late Phase 10 hands to G01 unchanged.
    """
    if not governance_enabled(world):
        return []
    from chronicler.politics import governing_cost_components
    events: list[Event] = []
    adj_map = {r.name: set(r.adjacencies) for r in world.regions}
    turn = world.turn
    for civ_idx, civ in enumerate(world.civilizations):
        gov = civ.governance
        if gov is None or not civ.regions:
            continue
        snapshot = _institution_snapshot(gov, turn)
        demand = _demand(snapshot)
        components = governing_cost_components(world, civ, adj_map)
        base = float(components[0]) if components is not None else 0.0
        projected = _pending_treasury(civ_idx, civ, acc)
        due = math.ceil(demand) if demand > 0 else 0
        paid = max(0, min(due, int(math.floor(max(0.0, projected)))))
        ratio = 1.0 if demand <= 0 or paid >= due else min(1.0, paid / demand)
        income = 0
        for inst in snapshot.institutions:
            effect = INSTITUTION_EFFECTS[inst.institution_type]
            weight = inst.legitimacy
            if effect.governing_cost_rebate:
                income += int(math.floor(base * effect.governing_cost_rebate * weight))
            if effect.treasury_per_region:
                income += int(math.floor(effect.treasury_per_region * len(civ.regions) * weight))
        _apply_stat(world, acc, civ_idx, civ, "treasury", income - paid, "keep")
        gov.funding_turn = turn
        gov.funding_treasury_before = projected
        gov.funding_treasury_after = projected - paid
        gov.last_base_governing_cost = base
        gov.last_institution_enforcement_cost = demand
        gov.last_institution_funding_ratio = ratio
        gov.last_enforcement_paid = paid
        if ratio < 1.0 and not gov.fiscal_crisis:
            gov.fiscal_crisis = True
            events.append(_event(world, "fiscal_crisis", civ,
                f"{civ.name}'s treasury can no longer pay for its institutions "
                f"({paid} of {due} owed).", 6))
        elif ratio >= 1.0 and gov.fiscal_crisis:
            gov.fiscal_crisis = False
    return events


def _funding_record(gov: CivGovernance, snapshot: g01.InstitutionSnapshot, civ,
                    turn: int) -> g01.FundingResult:
    demand = _demand(snapshot)
    if gov.funding_turn == turn and gov.last_institution_enforcement_cost == demand:
        return g01.FundingResult(snapshot, gov.funding_treasury_before, gov.funding_treasury_after,
                                 gov.last_base_governing_cost, demand,
                                 gov.last_institution_funding_ratio,
                                 g01.FundingPolicy.EXTERNAL_AGGREGATE_RECORD)
    # No Phase 2 record this turn (new or restored polity): nothing was paid.
    treasury = float(civ.treasury)
    ratio = 1.0 if demand <= 0 else 0.0
    gov.funding_turn = turn
    gov.funding_treasury_before = treasury
    gov.funding_treasury_after = treasury
    gov.last_base_governing_cost = 0.0
    gov.last_institution_enforcement_cost = demand
    gov.last_institution_funding_ratio = ratio
    gov.last_enforcement_paid = 0
    return g01.FundingResult(snapshot, treasury, treasury, 0.0, demand, ratio,
                             g01.FundingPolicy.EXTERNAL_AGGREGATE_RECORD)



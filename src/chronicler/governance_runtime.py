def _hostile(world, a: str, b: str) -> bool:
    rel = world.relationships.get(a, {}).get(b)
    return rel is not None and rel.disposition in (Disposition.HOSTILE, Disposition.SUSPICIOUS)


def _ambition_snapshot(world, civ_idx: int, civ, gov: CivGovernance, ctx: _Context,
                       legitimacy: float, capital: float, cursor: int,
                       for_generation: bool = False) -> g04.AmbitionSnapshot:
    """Copy live civ state into G04's snapshot.

    Target pools (conquerable/frontier/buildable/attainable) only matter when
    objectives are generated; evaluation reads ownership, routes and belief.
    """
    from chronicler.infrastructure import valid_build_types
    owned = set(civ.regions)
    conquerable, frontier = set(), set()
    for name in (civ.regions if for_generation else ()):
        region = ctx.region_map.get(name)
        if region is None:
            continue
        for adj in region.adjacencies:
            other = ctx.region_map.get(adj)
            if other is None or adj in owned:
                continue
            if other.controller is None:
                frontier.add(adj)
            elif other.controller != civ.name and _hostile(world, civ.name, other.controller):
                conquerable.add(adj)
    partners = ctx.partners.get(civ.name, set())
    active_partners = {str(ctx.civ_index[p]) for p in partners if p in ctx.civ_index}
    attainable = set()
    for other_name, rel in (world.relationships.get(civ.name, {}).items() if for_generation else ()):
        other_idx = ctx.civ_index.get(other_name)
        if other_idx is None or other_idx == civ_idx or other_name in partners:
            continue
        if not world.civilizations[other_idx].regions:
            continue
        if rel.disposition in (Disposition.NEUTRAL, Disposition.FRIENDLY, Disposition.ALLIED):
            attainable.add(str(other_idx))
    buildable = set()
    for name in (civ.regions if for_generation else ()):
        region = ctx.region_map.get(name)
        # A monument goal targets a region without standing works yet.
        if (region is not None and region.pending_build is None and name != civ.capital_region
                and not any(i.active for i in region.infrastructure)
                and valid_build_types(region, civ=civ, world=world)):
            buildable.add(name)
    faith = getattr(civ, "civ_majority_faith", 0xFF)
    predicates, observations = [], []
    if world.belief_registry and faith not in (None, 0xFF):
        for name in sorted(owned):
            region = ctx.region_map.get(name)
            if region is None:
                continue
            if ctx.rows is not None:
                dist = ctx.region_beliefs.get(ctx.region_index[name], {})
                total = sum(dist.values())
                share = dist.get(faith, 0) / total if total else 0.0
            else:
                share = 1.0 if region.majority_belief == faith else 0.0
            observations.append(g04.ConversionObservation(name, faith, belief_share=min(1.0, share)))
            if share < CONVERSION_CANDIDATE_SHARE:
                predicates.append(g04.ConversionPredicate(name, faith, minimum_share=CONVERSION_MINIMUM_SHARE))
    influence = civ.factions.influence
    ruler_faction = _ruler_faction(civ)
    return g04.AmbitionSnapshot(
        civ_id=str(civ_idx), ruler_id=gov.reign_id or "unset", turn=world.turn, event_cursor=cursor,
        legitimacy=min(1.0, max(0.0, legitimacy)), political_capital=max(0.0, capital),
        owned_regions=tuple(owned), conquerable_regions=tuple(conquerable), frontier_regions=tuple(frontier),
        active_trade_partners=tuple(active_partners), attainable_trade_partners=tuple(attainable),
        buildable_regions=tuple(buildable),
        military_eligible=civ.military >= 40 or ruler_faction is FactionType.MILITARY
        or influence.get(FactionType.MILITARY, 0.0) >= 0.30,
        clergy_eligible=bool(predicates) and (ruler_faction is FactionType.CLERGY
                                              or influence.get(FactionType.CLERGY, 0.0) >= 0.25),
        arts_available=civ.culture >= ARTS_CULTURE_THRESHOLD,
        trade_routes_exist=bool(ctx.routes),
        conversion_predicates=tuple(predicates), conversion_observations=tuple(observations),
    )


def _ambition_calibration(civ) -> g04.AmbitionCalibration:
    faction = _ruler_faction(civ)
    weights = {kind: 1.0 for kind in g04.AmbitionType if kind is not g04.AmbitionType.DIPLOMATIC_TRIUMPH}
    if faction is not None:
        primary, secondary = _FACTION_AMBITIONS[faction]
        weights[primary] = AMBITION_ALIGNED_WEIGHT
        weights[secondary] = max(weights[secondary], AMBITION_SECONDARY_WEIGHT)
    return g04.AmbitionCalibration(
        3 if len(civ.regions) >= 3 else 2, AMBITION_MIN_DURATION, AMBITION_MAX_DURATION,
        AMBITION_COMPLETION_LEGITIMACY, AMBITION_FAILURE_LEGITIMACY, tuple(weights.items()))


def _reign(gov: CivGovernance, civ_idx: int) -> g04.RulerAmbitions | None:
    if gov.reign_id is None:
        return None
    ambitions = []
    for a in gov.ambitions:
        predicate = None
        if a.conversion_faith_id is not None:
            predicate = g04.ConversionPredicate(a.target, a.conversion_faith_id,
                                                minimum_share=a.conversion_minimum_share)
        ambitions.append(g04.Ambition(g04.AmbitionType(a.ambition_type), a.target, a.generated_turn,
                                      a.deadline_turn, a.generated_event_cursor, predicate,
                                      a.completed, a.failed))
    return g04.RulerAmbitions(str(civ_idx), gov.reign_id, gov.accession_turn, gov.accession_event_cursor,
                              tuple(ambitions), tuple(gov.ruler_event_tags),
                              gov.last_evaluated_turn, gov.last_event_cursor)


def _store_reign(gov: CivGovernance, reign: g04.RulerAmbitions) -> None:
    gov.accession_turn = reign.accession_turn
    gov.accession_event_cursor = reign.accession_event_cursor
    gov.last_evaluated_turn = reign.last_evaluated_turn
    gov.last_event_cursor = reign.last_event_cursor
    gov.ruler_event_tags = list(reign.ruler_event_tags)
    gov.ambitions = [
        GovernanceAmbition(
            ambition_type=a.ambition_type.value, target=a.target, generated_turn=a.generated_turn,
            deadline_turn=a.deadline_turn, generated_event_cursor=a.generated_event_cursor,
            conversion_faith_id=a.conversion_predicate.faith_id if a.conversion_predicate else None,
            conversion_minimum_share=a.conversion_predicate.minimum_share if a.conversion_predicate else None,
            completed=a.completed, failed=a.failed)
        for a in reign.ambitions
    ]


def _evidence_events(world, civ, civ_idx: int, gov: CivGovernance, ctx: _Context) -> tuple[g04.EvidenceEvent, ...]:
    evidence = []
    for event in ctx.turn_events:
        if not event.actors or event.actors[0] != civ.name:
            continue
        if event.event_type == "infrastructure_completed":
            target = event.description.rsplit(" completed in ", 1)[-1] if " completed in " in event.description else None
        elif event.event_type == "cultural_work":
            # Patronage needs a named masterwork; routine cultural projection
            # (invest_culture) is too frequent to make the vow meaningful.
            target = None
        else:
            continue
        gov.evidence_cursor += 1
        evidence.append(g04.EvidenceEvent(world.turn, gov.evidence_cursor, str(civ_idx),
                                          event.event_type, target or None))
    return tuple(evidence)



def _war_outcomes(civ, ctx: _Context) -> tuple[int, int]:
    wins = losses = 0
    for event in ctx.turn_events:
        if event.event_type != "war" or len(event.actors) < 2 or civ.name not in event.actors[:2]:
            continue
        attacker = event.actors[0] == civ.name
        desc = event.description
        if "attacker_wins" in desc:
            wins, losses = (wins + 1, losses) if attacker else (wins, losses + 1)
        elif "defender_wins" in desc:
            wins, losses = (wins, losses + 1) if attacker else (wins + 1, losses)
    if len(civ.regions) < getattr(civ, "regions_start_of_turn", len(civ.regions)):
        losses += 1
    return wins, losses


def _dynasty_inputs(civ, gov: CivGovernance) -> tuple[g03.DynastyPrestigeInput, ...]:
    inputs = []
    successor_type = civ.leader.succession_type
    for number, record in enumerate(reversed(gov.reign_archive), start=1):
        if successor_type != "heir" or number > DYNASTY_DEPTH_LIMIT:
            break
        inputs.append(g03.DynastyPrestigeInput(number, max(0.0, record.cognomen_bonus)))
        successor_type = record.succession_type
    return tuple(inputs)


def _award_cognomen(gov: CivGovernance) -> tuple[str | None, float]:
    completed = sum(1 for a in gov.ambitions if a.completed)
    failed = sum(1 for a in gov.ambitions if a.failed)
    victories = len(gov.victory_turns)
    bonus = 0.05 * completed + 0.02 * min(victories, 5) - 0.03 * failed
    if gov.ruler_legitimacy >= 0.8:
        bonus += 0.03
    bonus = round(min(0.25, max(0.0, bonus)), 6)
    if bonus <= 0:
        return None, 0.0
    if victories >= 3:
        name = "the Conqueror"
    elif any(a.completed and a.ambition_type == "build_monument" for a in gov.ambitions):
        name = "the Builder"
    elif any(a.completed and a.ambition_type == "religious_conversion" for a in gov.ambitions):
        name = "the Pious"
    elif any(a.completed and a.ambition_type == "patron_of_arts" for a in gov.ambitions):
        name = "the Magnificent"
    elif bonus >= 0.15:
        name = "the Great"
    else:
        name = "the Wise"
    return name, bonus



"""Live Phase 8 governance: the M63a/M65a/M66a/M66b kernels inside the turn loop.

The four detached kernels (``institutions`` G01, ``elite_metrics`` G02,
``governance_capital`` G03, ``ruler_ambitions`` G04) are pure and fully
validated. This adapter supplies them with real simulation observations,
persists their carry on ``Civilization.governance`` and turns their outputs into
consequences: stability, faction influence, treasury, succession-crisis risk,
revolts/civil wars, secession suppression, and an action-weight bucket.

Turn placement (roadmap "Execution Ownership & Turn Ordering"):

* Phase 2 (``fund_institutions_phase2``), right after ``apply_governing_costs``:
  institutional enforcement demand is paid from the treasury, recording the
  M63a funding bookkeeping (base cost, demand, coverage ratio) for turn N.
* Phase 5 (``governance_weight_modifiers``): the governance bucket of action
  weights (institutions, ambitions, legitimacy, PSI), clamped to 1.5x as one
  bucket before the existing global 2.5x cap (REVIEW B-5 / decision D1).
* Late Phase 10 (``tick_governance``), after the Rust/Python politics pass and
  ``tick_factions``: institutions resolve against the turn-N funding record,
  political capital is spent in fixed priority (force repeal, enact, suppress),
  elite metrics are computed from the post-agent snapshot (or an aggregate
  proxy with ``--agents off``), ambitions are generated/evaluated, legitimacy
  and capital accrue, and PSI is advanced. All outputs are effective N+1;
  same-turn politics already ran and is never revisited.

The politics pass consumes governance only through ordinary civ state
(stability, treasury, factions), so the Rust politics runtime and the Python
oracle see identical inputs and no FFI schema change is needed.

Every random draw uses ``stable_hash_int`` with a labelled reserved stream
(roadmap offsets 1000/1200/1900 plus 1300 for stress), never the action RNG.
Disabled worlds never import or call this module's tick functions.
"""

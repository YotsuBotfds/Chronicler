def governance_weight_modifiers(civ, world) -> dict[ActionType, float]:
    """Governance contributor bucket for action weights (M63b, decision D1).

    Institutions (scaled by their legitimacy), the ruler's open ambitions,
    legitimacy and PSI multiply into one per-action factor that is clamped to
    ``[1/1.5, 1.5]`` before the existing global 2.5x cap applies.
    """
    gov = getattr(civ, "governance", None)
    if gov is None or not governance_enabled(world):
        return {}
    mods = {a: 1.0 for a in _ACTIONS}
    for inst in gov.institutions:
        effect = INSTITUTION_EFFECTS[g01.InstitutionType(inst.institution_type)]
        for action, m in effect.actions.items():
            mods[action] *= 1.0 + (m - 1.0) * inst.legitimacy
    for ambition in gov.ambitions:
        if ambition.completed or ambition.failed:
            continue
        for action, m in AMBITION_ACTION_BIAS.get(g04.AmbitionType(ambition.ambition_type), {}).items():
            mods[action] *= m
    if getattr(world, "gp_agendas", None) is not None:
        # Great-person agendas (--gp-agendas) share this bucket and its clamp.
        from chronicler.gp_agendas import agenda_weight_factors
        for action, m in agenda_weight_factors(world, civ).items():
            mods[action] *= m
    if gov.psi_crisis:
        mods[A.DEVELOP] *= 1.1
        mods[A.WAR] *= 0.9
    if gov.ruler_legitimacy < 0.3:
        mods[A.WAR] *= 1.1  # diversionary war
    if gov.government_form is not None:
        ws = gov.selectorate_ratio
        if ws < SMALL_COALITION:      # private goods for a narrow coalition
            mods[A.WAR] *= 1.1
            mods[A.BUILD] *= 1.05
        elif ws >= LARGE_COALITION:   # public goods for a broad coalition
            mods[A.DEVELOP] *= 1.1
            mods[A.TRADE] *= 1.1
    floor = 1.0 / GOVERNANCE_WEIGHT_CEILING
    return {a: min(GOVERNANCE_WEIGHT_CEILING, max(floor, m)) for a, m in mods.items() if m != 1.0}


def governance_crisis_multiplier(civ, world) -> float:
    """Succession-crisis probability multiplier from legitimacy, institutions, PSI."""
    gov = getattr(civ, "governance", None)
    if gov is None or not governance_enabled(world):
        return 1.0
    mult = 1.5 - gov.ruler_legitimacy
    for inst in gov.institutions:
        effect = INSTITUTION_EFFECTS[g01.InstitutionType(inst.institution_type)]
        mult *= 1.0 + (effect.crisis_multiplier - 1.0) * inst.legitimacy
    if gov.psi_crisis:
        mult *= 1.3
    if gov.government_form is not None and SMALL_COALITION <= gov.selectorate_ratio < LARGE_COALITION:
        mult *= TRANSITION_TRAP_CRISIS_MULTIPLIER
    return mult



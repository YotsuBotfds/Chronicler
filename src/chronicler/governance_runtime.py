def _rng(label: str, world, offset: int, *parts) -> random.Random:
    return random.Random(stable_hash_int(label, world.seed, world.turn, offset, *parts))


def _faction_weights(civ) -> g01.FactionWeights:
    raw = [max(0.0, float(civ.factions.influence.get(ft, 0.0))) for ft in _FACTIONS]
    total = math.fsum(raw)
    if total <= 0:
        raw, total = [1.0] * len(_FACTIONS), float(len(_FACTIONS))
    values = [min(1.0, v / total) for v in raw]
    return g01.FactionWeights(*values)


def _ruler_faction(civ) -> FactionType | None:
    from chronicler.factions import TRAIT_FACTION_MAP
    return TRAIT_FACTION_MAP.get(civ.leader.trait)


def _dominant_faction(civ) -> FactionType | None:
    best = max(_FACTIONS, key=lambda ft: (civ.factions.influence.get(ft, 0.0), -_FACTIONS.index(ft)))
    if civ.factions.influence.get(best, 0.0) > g01.FACTION_DOMINANCE_THRESHOLD:
        return best
    return None


def _institution_snapshot(gov: CivGovernance, turn: int) -> g01.InstitutionSnapshot:
    states = tuple(
        g01.InstitutionState(g01.InstitutionType(i.institution_type), i.enacted_turn,
                             float(min(1.0, max(0.0, i.legitimacy))), float(i.enforcement_cost),
                             g01.Faction(i.opposing_faction))
        for i in gov.institutions
    )
    return g01.InstitutionSnapshot(turn, states)


def _store_institutions(gov: CivGovernance, snapshot: g01.InstitutionSnapshot) -> None:
    gov.institutions = [
        GovernanceInstitution(institution_type=i.institution_type.value, enacted_turn=i.enacted_turn,
                              legitimacy=i.legitimacy, enforcement_cost=i.enforcement_cost,
                              opposing_faction=i.opposing_faction.value)
        for i in snapshot.institutions
    ]
    gov.institutions_effective_turn = snapshot.effective_turn


def _demand(snapshot: g01.InstitutionSnapshot) -> float:
    return math.fsum(i.enforcement_cost for i in snapshot.institutions)


def _active_types(gov: CivGovernance) -> list[g01.InstitutionType]:
    return [g01.InstitutionType(i.institution_type) for i in gov.institutions]


def _quantize_capital(value: Fraction) -> Fraction:
    value = min(max(value, Fraction(0)), MAX_POLITICAL_CAPITAL)
    return Fraction(math.floor(value * CAPITAL_QUANTUM), CAPITAL_QUANTUM)


def _pending_treasury(civ_idx: int, civ, acc) -> float:
    projected = float(civ.treasury)
    for change in getattr(acc, "_changes", ()) if acc is not None else ():
        if change.civ_id == civ_idx and change.category == "keep" and change.stat == "treasury":
            projected += change.delta
    return projected


def _apply_stat(world, acc, civ_idx: int, civ, stat: str, delta: int, category: str = "signal") -> None:
    if not delta:
        return
    if acc is not None:
        acc.add(civ_idx, civ, stat, delta, category)
    elif stat in ("treasury", "prestige"):
        # Unbounded stats floor at zero, matching StatAccumulator.apply().
        setattr(civ, stat, max(0, getattr(civ, stat) + delta))
    else:
        setattr(civ, stat, clamp(getattr(civ, stat) + delta, STAT_FLOOR.get(stat, 0), 100))


def _event(world, event_type: str, civ, description: str, importance: int,
           actors: list[str] | None = None) -> Event:
    return Event(turn=world.turn, event_type=event_type, actors=actors or [civ.name],
                 description=description, importance=importance)


